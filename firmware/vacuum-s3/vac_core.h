  float load;             /* загрузка фильтра, % до порога серии */
  float depth;            /* последний удар: провал разрежения, доля (1 — до атмосферы) */
  float in_health;        /* фильтр клапанов: сила удара от чистого, % */
  uint32_t faults;
  uint16_t next_series;   /* секунд до серии */
