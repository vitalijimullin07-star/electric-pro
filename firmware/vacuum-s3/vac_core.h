/*
 * Контроллер строительного пылесоса «S3» на ESP32-S3 (плата на готовых модулях): две турбины
 * Domel 1600 Вт — каждая через модуль реле 30 А и симисторный регулятор МР248 (ШИМ 0–3,3 В →
 * мощность 0–100 %), регулятор расхода воздуха, фильтр 280×210 в коробке (камера ~3 л) и два
 * тарельчатых клапана (как у Kärcher Tact и Bosch AFC): удерживающий магнит через твердотельное
 * реле G3MB держит тарелку против разрежения, на удар ток снимается на 80–120 мс (целое число
 * полупериодов — SSR переключается в нуле сети), тарелку вталкивает разрежение, атмосфера бьёт по
 * фильтру обратным потоком, пружины закрывают тарелку, магнит её ловит. Тарелка не села —
 * турбины сбрасываются, пока пружины её не закроют. Или импульсные клапаны на соленоидах 230 В
 * («set valves pulse»): удар 30–80 мс током. Пылеудаление не прерывается — тянет разрежение бака.
 * Режимы очистки (удары, промежуток, длина удара, пауза) и «Авто», который подбирает их
 * по поведению фильтра; мощная очистка при закрытом шланге; паспорт фильтров А и Б.
 * Розетка инструмента через модуль реле 30 А: автозапуск по току (трансформатор тока) или по
 * Bluetooth-метке на аккумуляторном инструменте, выбег и удары после инструмента, предел
 * общего тока с выбором на экране. Датчики: токи турбин и инструмента (SCT-013, выход 1 В),
 * температуры двигателей, разрежение (MPX5100DP), перепад на фильтре и расход (SDP810/SDP811),
 * электроды уровня и перелива в баке, поплавок. Кнопки пульта, «Турбина 1», «Турбина 2», «Выкл»
 * и кнопка энкодера — через расширитель PCA9555; энкодер — на выводах ESP32; беспроводной пульт и
 * метки — Bluetooth (до 4 устройств). Экран 3,5″ ILI9488 с касанием — прямо на контроллере
 * (интерфейс пульта работает внутри прошивки), или отдельная плата с экраном по UART.
 */
