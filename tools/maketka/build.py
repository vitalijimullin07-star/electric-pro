def main():
    dump, out = Path(sys.argv[1]), Path(sys.argv[2])
    parts = L.load_parts(dump)
    ref_nets = L.reference_nets(parts)
    variants = {}
    for dk in (22.86, 25.4):
        for pc in (20.32, 15.24):
            lay = L.Layout(parts, dk, pc)
            lay.build()
            # Подписи выводов клеммников (до проводов: концы проводов берут имя вывода);
            # на этажерке у повёрнутых на 90° и 180° порядок обратный (term() в stack.ts).
            for ref, labels in TERMINAL_LABELS.items():
                lab = labels[::-1] if ref in TERMINAL_REV else labels
                for q in lay.placed[ref]['pins']:
                    q['name'] = lab[int(q['n']) - 1]
                    assert LABEL_NET[q['name']] == q['net'], (ref, q)
            lay.connect()
            probs = lay.check(ref_nets)
            if probs:
                print('\n'.join(probs))
                sys.exit(1)
            variants[f'{dk}/{pc}'] = {'placed': lay.placed, 'trans': lay.trans, 'wires': lay.wires, 'displayHoles': lay.display_holes, 'encoderTabs': lay.encoder_tabs}
            print(f'{dk}/{pc}: проводов {len(lay.wires)}, переходов {len(lay.trans)}')
    first = next(iter(variants.values()))
    info = {}
    for ref in first['placed']:
        p = parts[ref]
        kname, kcls = kind_of(p['fid'])
        info[ref] = {'value': p['value'], 'desc': p['description'], 'kind': kname, 'cls': kcls}
    groups = [{'id': g, 'name': n, 'pref': pref, 'nets': nets} for g, n, pref, nets in GROUPS]
    all_nets = {q['net'] for pl in first['placed'].values() for q in pl['pins'] if q['net']}
    missing = sorted(all_nets - {n for g in GROUPS for n in g[3]})
    assert not missing, missing
    data = {
        'variants': variants, 'parts': info, 'groups': groups, 'netText': NET_TEXT, 'bom': bom(parts, first['placed']),
        'headers': L.HEADERS, 'standoffs': L.STANDOFFS, 'rows': L.ROW_NAMES, 'cols': L.COLS, 'nrows': L.ROWS,
    }
    tpl = (Path(__file__).parent / 'template.html').read_text(encoding='utf-8')
    out.write_text(tpl.replace('/*DATA*/null', json.dumps(data, ensure_ascii=False, separators=(',', ':'))), encoding='utf-8')
