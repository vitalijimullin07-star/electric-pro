import { exportNetlistText } from '../../io/bom';
import type { Project } from '../../model/types';

/** Памятка к проекту «Квазар»: провода, биты конфигурации, катушка, симуляция, список соединений. */
export function quasarNotes(p: Project): string {
  const comps = Object.values(p.components);
  const byRef = new Map(comps.map((c) => [c.ref, c]));
  const netName = (id: string | undefined) => (id ? (p.nets[id]?.name ?? '?') : '—');
  // Куда идёт каждый провод с платы: площадки X… → выводы выносных деталей той же цепи.
  const wires: string[] = [];
  // Провод земли показываем только к «своей» детали.
  const own: Record<string, RegExp> = { X1: /^GB/, X10: /^GB/, X2: /^HG/, X7: /^HG/, X8: /^HG/, X3: /^(SW|VD)/, X9: /^(SW|VD)/, X4: /^BA/, X5: /^L3$/, X6: /^(L3|C35)$/ };
  for (const c of comps.filter((x) => !x.offBoard && /^X\d/.test(x.ref)).sort((a, b) => a.ref.localeCompare(b.ref, 'ru', { numeric: true }))) {
    const fp = p.footprints[c.footprint];
    for (const pad of fp.pads) {
      const net = c.padNets[pad.number];
      const ends: string[] = [];
      for (const o of comps.filter((x) => x.offBoard && (netName(net) !== 'GND' || !own[c.ref] || own[c.ref].test(x.ref)))) {
        const ofp = p.footprints[o.footprint];
        for (const q of ofp.pads) if (o.padNets[q.number] === net) ends.push(`${o.ref}.${q.name && q.name !== q.number ? q.name : q.number}`);
      }
      wires.push(`  ${c.ref} «${pad.name ?? pad.number}» (${netName(net)}) → ${ends.join(', ') || '—'}`);
    }
  }
  const star = comps.filter((c) => /\*/.test(c.value)).map((c) => `  ${c.ref} ${c.value} — ${c.description ?? ''}`.trimEnd());
  const keys = ['SW1', 'SW2', 'SW3', 'SW4', 'SW5', 'SW6'].map((r) => `  ${r} — ${byRef.get(r)?.description ?? ''}`);
  return [
    'Металлоискатель «Квазар AVR» — плата DesAlex, прошивка Andy_F',
    '=============================================================',
    '',
    'Схема и прошивка: Andy_F, http://fandy.ucoz.org (Quasar AVR, прошивки 1.38 и 1.4.5).',
    'Плата под ЛУТ на выводных деталях: DesAlex (Sprint Layout 5, файл «Quasar AVR board from DesAlex.lay»).',
    'Перенос в Plata: разводка взята из файла как есть, детали и выводы сверены со сборочным чертежом,',
    'цепи восстановлены по меди и названы как на схеме Andy_F.',
    '',
    'Файлы',
    '  quasar-avr-desalex.plata.json        — проект с прошивкой 1.4.5 (открыть: Файл → Открыть файл проекта)',
    '  quasar-avr-desalex-fw138.plata.json  — то же с прошивкой 1.38 из архива DesAlex',
    '  quasar-avr-desalex-perechen.csv      — перечень элементов',
    '',
    'Контроллер и биты конфигурации',
    '  ATmega32A-PU (DIP-40), кварц 11,0592 МГц.',
    '  LOW = 0x3F: внешний кварц, CKSEL = 1111, SUT = 11 (16K CK + 64 мс), BOD включён.',
    '  HIGH = 0xD9: JTAG выключен (PC2–PC5 заняты дисплеем), SPIEN включён.',
    '  Если кварц не запускается — запрограммируйте CKOPT (HIGH = 0xC9).',
    '',
    'Отличия платы DesAlex от схемы Andy_F',
    '  • Детали выводные: IRF9640 + IRF840 вместо сборки IRF7105, MCP601 вместо MCP633,',
    '    L4940V5 вместо LM2941, LM2931 вместо LP2950, C945/A733 вместо BC846/BC857.',
    '  • AREF соединён с +5 В — опора АЦП контроллера 5 В вместо встроенных 2,56 В.',
    '    Поэтому шунт тока R9 — 1,8 Ом (у Andy_F 1 Ом), делитель батареи R29 — 4,3 кОм (у Andy_F 10 кОм):',
    '    так показания тока и напряжения на экране остаются верными.',
    '  • Нет диода защиты от переполюсовки (D7 у Andy_F) и светодиода HLED — вывод PB4 свободен.',
    '  • Выводы PB0–PB3 соединены вместе — все четыре качают передатчик (так и задумано в прошивке,',
    '    её самотест это проверяет).',
    '  • Сток транзисторов TO-220 — средний отогнутый вывод (подписи D/S на сборочном чертеже перепутаны).',
    '',
    'Подбираются при настройке (звёздочка)',
    ...star,
    '',
    'Провода с платы к выносным деталям',
    ...wires,
    '  На дисплее HG1: RW и V0 — на общий провод (или V0 через подстроечный резистор 10 кОм для контраста).',
    '',
    'Клавиатура (6 кнопок на трёх линиях B1–B3, диоды VD1–VD4 1N4148)',
    ...keys,
    '',
    'Датчик DD (из описания Andy_F)',
    '  Внешний диаметр 230 мм. TX — 40–45 витков провода 0,5 мм, RX — 200 витков провода 0,2 мм.',
    '  TX — последовательный резонанс с C6 (0,3–0,47 мкФ, подбирается), рабочая частота 4,5–9 кГц',
    '  (в макете 8,192 кГц). RX — параллельный резонанс с C35 0,033 мкФ, настраивается на 1,5–2 кГц ниже TX.',
    '',
    'Симуляция в Plata',
    '  Симуляция → Старт. Прошивка уже в проекте. Контроллер ATmega32A на 11,0592 МГц, частота — по кварцу BQ1.',
    '  Вкладка «Детали»: экран дисплея, кнопки SW1–SW6 (нажать и держать), аккумулятор (напряжение),',
    '  катушка L3: цель (железо, фольга, золото, никель, алюминий, медь, серебро, феррит), глубина,',
    '  «Провести над целью» — катушка проходит над целью за секунду, на шкале появляется метка VDI,',
    '  в динамике — тон: низкий у железа, высокий у хороших проводников.',
    '  Что моделируется: самотест портов, передатчик на PB0–PB3 с резонансом катушки (ток виден на шунте R9),',
    '  АЦП MCP3201 по SPI с сигналом приёмника, делитель батареи, подсветка (ШИМ таймера 2 через Q4),',
    '  звук (ШИМ таймера 1 через Q2 и Q3), клавиатура с диодами, память настроек (EEPROM).',
    '  Сигнал приёмника — упрощённая модель: синусоида частоты TX, разбаланс катушки и отклик цели',
    '  с фазой по металлу. Грунт и помехи не моделируются.',
    '',
    exportNetlistText(p),
  ].join('\n');
}
