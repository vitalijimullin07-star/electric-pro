    '  состояние, пуск, стоп, уставка, мощность (прошивка по воздуху не сделана: обновление — по проводу).',
    '',
    'Управление (экраны пульта — как в макете)',
    '  «Пуск турбин»: коротко — пуск и стоп, удержание — экран пресетов. Энкодер меняет то, что',
    '  выделено на экране: на «Работе» — уставку расхода (авто) или мощность (ручной).',
    '  Работа — расход крупно, уставка, скорость воздуха, разрежение, загрузка турбин, фильтр,',
    '  неисправности. Режим — Авто (ПИ-регулятор по расходу), Ручной (фиксированная мощность),',
    '  Выкл; розетка инструмента (турбины — по инструменту), уборка остатка, вторая турбина.',
    '  Очистка — ударов в серии, импульс, пауза, порог R, разгон; авто / выкл; «Продуть», «Полная».',
    '  Фильтр — R сейчас, после удара, R нового, порог мойки (2,5 × R нового), съём, число ударов;',
    '  «Фильтр новый» и «Сброс счётчика» — касанием дважды. Журнал — наработка и приведённые часы',
    '  турбин, ресурс щёток, R чистый по сменам (смена — включение питания), аварии, экспорт в порт.',
