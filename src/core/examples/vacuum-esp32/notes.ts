import { exportNetlistText } from '../../io/bom';
import type { Project } from '../../model/types';
import { VAC_BOARD } from './build';

/** Памятка к проекту «Пылесос на ESP32»: сборка, провода, прошивка, управление, защиты, симуляция. */
export function vacuumNotes(p: Project): string {
  const comps = Object.values(p.components);
  const netName = (id: string | undefined) => (id ? (p.nets[id]?.name ?? '?') : '—');
  // Разъёмы платы: вывод → цепь → куда идёт провод (выводы выносных деталей той же цепи).
  const wires: string[] = [];
  for (const c of comps.filter((x) => !x.offBoard && /^X[TS]?\d/.test(x.ref)).sort((a, b) => a.ref.localeCompare(b.ref, 'ru', { numeric: true }))) {
    wires.push(`  ${c.ref} «${c.value}»: ${c.description ?? ''}`);
    const fp = p.footprints[c.footprint];
    for (const pad of [...fp.pads].sort((a, b) => a.number.localeCompare(b.number, 'en', { numeric: true }))) {
      const net = c.padNets[pad.number];
      if (!net) continue;
      const name = netName(net);
      const ends: string[] = [];
      if (!/^(GND|3V3|5V)$/.test(name))
        for (const o of comps.filter((x) => x.offBoard)) {
          const ofp = p.footprints[o.footprint];
          for (const q of ofp.pads) if (o.padNets[q.number] === net) ends.push(`${o.ref}.${q.name && q.name !== q.number ? q.name : q.number}`);
        }
      wires.push(`    ${pad.number} ${name}${ends.length ? ` → ${ends.join(', ')}` : ''}`);
    }
  }
  const off = comps
    .filter((c) => c.offBoard)
    .sort((a, b) => a.ref.localeCompare(b.ref, 'ru', { numeric: true }))
    .map((c) => `  ${c.ref.padEnd(4)} ${c.value.padEnd(16)} ${c.description ?? ''}`.trimEnd());
  return [
    'Контроллер строительного пылесоса на ESP32 — плата, прошивка, симуляция',
    '======================================================================',
    '',
    'Две турбины по 1200 Вт с плавным пуском и фазовым управлением, розетка для инструмента',
    'с автозапуском, продувка двух фильтров клапанами, датчики тока, температуры двигателей,',
    'разрежения, перепада на фильтре и расхода воздуха, экран, энкодер, три кнопки, зуммер, Wi-Fi.',
    'Готовых модулей нет, кроме ESP32-WROOM-32E, датчиков и экрана OLED на панели: блок питания,',
    '«диммеры», детектор нуля, обвязка датчиков — на самой плате.',
    '',
    'ВНИМАНИЕ: на плате и проводах — сеть 230 В. Собирать и проверять без сети; прошивать —',
    'только от переходника USB-UART при отключённой сети; в корпусе — зазоры и изоляция, PE на корпус.',
    '',
    'Файлы',
    '  vacuum-esp32.plata.json          — проект: схема, плата, прошивка для симуляции (Файл → Открыть файл проекта)',
    '  vacuum-esp32-perechen.csv        — перечень элементов',
    '  vacuum-esp32-proshivka.bin       — прошивка ESP32 целиком (загрузчик + таблица разделов + программа), писать с адреса 0x0',
    '  firmware/vacuum-esp32/ в репозитории — исходники прошивки (Arduino IDE / arduino-cli) и сборка ядра в WebAssembly',
    '',
    'Плата',
    `  ${VAC_BOARD.w}×${VAC_BOARD.h} мм, два слоя, FR-4 1,6 мм, медь 35 мкм. Дорожки от 0,2 мм, зазор 0,2 мм,`,
    '  переходные 0,6/0,3 и 0,8/0,4 мм — обычные нормы заводов (JLCPCB, PCBWay, Резонит).',
    '  Сверху — зона 230 В: клеммники, предохранитель, варистор, первичка трансформатора, выходы',
    '  оптронов, симисторы клапанов. Снизу — низковольтная часть. Между ними не меньше 6 мм',
    '  (класс цепей Mains), под оптронами — прорезь 1,2 мм для пути утечки.',
    '  Под антенной ESP32 меди нет (антенна — к краю платы), под брюхом модуля — только нижний слой.',
    '  Земля — заливкой с обеих сторон, аналоговая земля датчиков — шиной снизу к разъёму X4.',
    '',
    'Питание',
    '  Трансформатор 230/9 В 2 ВА → мост MB6S → SS14 → 470 мкФ (≈12 В) → AP63205 (5 В) → AMS1117 (3,3 В).',
    '  Детектор нуля — с выпрямленной вторички до конденсатора (SS14 их развязывает): транзистор',
    '  закрыт у нуля сети, на входе ESP32 короткий импульс «1»; по его ширине прошивка оценивает',
    '  напряжение сети.',
    '',
    'Разъёмы и провода',
    ...wires,
    '',
    'Детали вне платы',
    ...off,
    '  Симисторы BTA41-600B — на радиаторе (≈1,5 °C/Вт на обе турбины), выводы T1 — общий провод L,',
    '  T2 — к двигателю через окно трансформатора тока, G — к клеммнику XT3.',
    '  Провод двигателя продевается в окно трансформатора тока ZMCT103C (один виток).',
    '',
    'Прошивка',
    '  Arduino IDE 2 или arduino-cli, пакет плат esp32 от Espressif версии 3.x, плата «ESP32 Dev Module».',
    '  Открыть firmware/vacuum-esp32/vacuum-esp32.ino (остальные файлы папки подтянутся сами).',
    '  Загрузка через X6 и переходник USB-UART 3,3 В (CP2102, CH340): TX переходника → RXD, RX → TXD,',
    '  GND, 3V3. Перемычка IO0–GND, подать питание, загрузить, снять перемычку, перевключить.',
    '  Готовый файл: esptool.py --chip esp32 --baud 460800 write_flash 0x0 vacuum-esp32-proshivka.bin',
    '  Wi-Fi: точка «Pylesos-XXXX», пароль 12345678, страница http://192.168.4.1 — состояние,',
    '  пуск, стоп, мощность (прошивка по воздуху не сделана: обновление — через X6).',
    '',
    'Управление',
    '  «Пуск/Стоп» — включить и выключить; в режиме «Авто» пуск взводит пылесос, турбины',
    '  включаются вместе с инструментом в розетке и работают ещё «выбег» секунд после него.',
    '  «Режим» — ручной / авто. «Продувка» — продуть фильтры (повторное нажатие — отмена).',
    '  Энкодер — мощность 30…100 %; нажатие — меню, долгое нажатие — выход из меню.',
    '  Меню: мощность, какие турбины (обе/1/2), выбег, порог тока инструмента, автопродувка по',
    '  перепаду на фильтре, число и длительность импульсов, продувка после остановки, порог',
    '  скорости воздуха в шланге, диаметр шланга, плавный пуск, калибровка сети, сдвиг нуля,',
    '  коэффициент расходомера, экран, наработка турбин. Настройки хранятся во флеш-памяти.',
    '  Монитор порта 115200: help, status, start, stop, auto, manual, purge, power N, turbines 0|1|2.',
    '',
    'Защиты',
    '  Нет синхронизации с сетью — ключи не открываются. Напряжение сети вне 190…250 В — предупреждение.',
    '  Перегрузка турбины (больше 9 А) — отключение на 30 с. Нет тока при открытом симисторе — обрыв',
    '  обмотки или щёток. Ток при закрытом симисторе — пробит симистор (турбина не остановится!).',
    '  Термисторы: 95 °C — мощность снижается, 110 °C — турбина отключается до 80 °C.',
    '  Мало воздуха в шланге и засор (большое разрежение при малом расходе) — сигнал и надпись.',
    '  Фильтр забит (перепад, пересчитанный на 200 м³/ч, выше порога) — автопродувка.',
    '',
    'Симуляция в Plata',
    '  Симуляция исполняет то же ядро прошивки на C (vac_core, vac_ui, vac_drv), собранное в',
    '  WebAssembly: обработка кнопок, меню, экран, регуляторы, защиты — точно как в ESP32. Сам',
    '  процессор Xtensa не эмулируется: вместо обвязки Arduino (hal_esp32.cpp) — обвязка симуляции',
    '  (sim_wasm.c), таймер 100 мкс и прерывание детектора нуля вызываются по времени симуляции.',
    '  Модель установки: сеть 50/60 Гц, детектор нуля, оптроны и симисторы (угол открытия),',
    '  коллекторные двигатели с вентиляторами, нагрев обмоток, шланг, бак, два фильтра с пылью,',
    '  клапаны продувки, розетка с инструментом, трансформаторы тока, термисторы, датчики давления',
    '  (MPX5050DP — аналоговый, SDP810 — по I²C), экран SSD1306, энкодер, кнопки, зуммер.',
    '  Всё меняется на ходу: напряжение сети, провал, шланг (длина, диаметр, перекрытие), пыль,',
    '  засор фильтра, мощность и износ двигателей, обрыв обмотки, пробой симистора, клапан не',
    '  открывается, мощность инструмента, температура воздуха и ускорение нагрева.',
    '  Вкладка «Симуляция» → «Во весь экран»: пульт, мнемосхема с турбинами и воздухом, графики',
    '  оборотов, токов, разрежения и температуры, все настройки деталей и монитор порта.',
    '',
    'Соединения (для проверки)',
    exportNetlistText(p),
  ].join('\n');
}
