    'пробитого симистора) и симистор BTA24 с фазовым управлением (плавный пуск, регулятор расхода,',
    'пуск по очереди). Фильтр 180×320 — две половины, у каждой свой клапан продувки Ø40 с соленоидом',
    '230 В (4 кгс) через MOC3063 + BTA08. Датчики: токи турбин и клапанов, температура двигателей,',
    'разрежение, перепад на фильтре, расход, электроды уровня и перелива в баке, поплавок.',
    'Пульт — плата ESP32-S3 с сенсорным экраном 7″ 800×480; по бокам экрана — шесть кнопок (три',
    'слева, три справа), внизу посередине — энкодер (меню и мощность, можно в перчатках), ниже —',
    '«Турбина 1», «Турбина 2», «Выкл». Беспроводной пульт Bluetooth — две кнопки и энкодер.',
    '',
    'ВНИМАНИЕ: на плате и проводах — сеть 230 В. Собирать и проверять без сети; прошивать через USB-C',
    'только при выключенной сети (выключатель SA1); в корпусе — зазоры и изоляция, PE на корпус.',
