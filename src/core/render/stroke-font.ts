const parsed = new Map<string, Vec2[][]>();
function glyph(ch: string): Vec2[][] {
  let up = ch in G ? ch : ch.toUpperCase();
  if (!(up in G)) up = '?';
  const hit = parsed.get(up);
  if (hit) return hit;
  const strokes = (G[up] ?? '')
    .split('|')
    .filter((s) => s.trim())
    .map((s) => s.trim().split(/\s+/).map((pt) => {
      const [x, y] = pt.split(',').map(Number);
      return { x, y };
    }));
  parsed.set(up, strokes);
  return strokes;
}

/** Высота заглавной буквы = size; ширина знакоместа. */
export const ADVANCE = 5 / 6;
export const CAP = 1;

export interface TextSpec {
  text: string;
  at: Vec2;
  size: number;
  rotation?: number;
  align?: 'left' | 'center' | 'right';
  /** Зеркалить (надписи на нижней стороне). */
  mirror?: boolean;
}

export function textWidth(text: string, size: number): number {
  return Math.max(0, text.length * ADVANCE * size - (1 / 6) * size);
}

/** Штрихи текста в мировых координатах (мм). Точка at — центр строки по вертикали. */
export function textStrokes(t: TextSpec): Vec2[][] {
  const k = t.size / 6;
  const w = textWidth(t.text, t.size);
  const align = t.align ?? 'center';
  const startX = align === 'left' ? 0 : align === 'right' ? -w : -w / 2;
  const out: Vec2[][] = [];
  let x = startX;
  for (const ch of t.text) {
    for (const stroke of glyph(ch)) {
      out.push(
        stroke.map((p) => {
          let lx = x + p.x * k;
          const ly = -(p.y * k - 3 * k); // центр строки на нулевой высоте, ось Y вниз
          if (t.mirror) lx = -lx;
          return add(rotate({ x: lx, y: ly }, t.rotation ?? 0), t.at);
        }),
      );
    }
    x += ADVANCE * t.size;
  }
  return out;
}

/** Есть ли в шрифте все символы (для предупреждения). */
export function unsupportedChars(text: string): string[] {
  return [...new Set([...text].filter((c) => !(c in G) && !(c.toUpperCase() in G)))];
}
